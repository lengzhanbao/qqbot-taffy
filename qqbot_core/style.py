_TAFFY_IDENTITY_MARKERS = ("塔菲", "taffy", "小菲", "塔不灭")
_TAFFY_EMOTION_MARKERS = ("喵", "嘻嘻", "哈哈", "讨口子", "不是", "！")


def _is_taffy_styled(reply):
    text = (reply or "").lower()
    has_identity = any(marker in text for marker in _TAFFY_IDENTITY_MARKERS)
    has_emotion = any(marker in text for marker in _TAFFY_EMOTION_MARKERS)
    return has_identity and has_emotion


def _append_search_source_marker(
    reply,
    search_returned,
    search_attempted=False,
    taffy_enabled=True,
):
    """回答末尾标注本次是否来自网络搜索。"""
    if not reply:
        return reply
    markers = _SEARCH_SOURCE_MARKERS + _NEUTRAL_SEARCH_SOURCE_MARKERS
    if not search_returned and not search_attempted:
        for marker in markers:
            reply = reply.replace(marker, "")
        return reply.rstrip()
    if taffy_enabled:
        if any(marker in reply for marker in markers):
            return reply
    else:
        if any(marker in reply for marker in _NEUTRAL_SEARCH_SOURCE_MARKERS):
            return reply
        for marker in _SEARCH_SOURCE_MARKERS:
            reply = reply.replace(marker, "").rstrip()
    if taffy_enabled and search_returned:
        marker = "（联网搜过喵）"
    elif taffy_enabled and search_attempted:
        marker = "（联网未找到可靠结果，塔菲暂时不确定喵）"
    elif taffy_enabled:
        marker = "（没联网，塔菲凭现有知识答的喵）"
    elif search_returned:
        marker = "（已联网搜索）"
    elif search_attempted:
        marker = "（已尝试联网，但未找到有效结果）"
    else:
        marker = "（未联网）"
    return reply.rstrip() + "\n\n" + marker
